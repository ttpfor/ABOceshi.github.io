function score(answers) {
  return profiles.map(profile => {
    let total = 0;
    const ranked = profile.groups.map((group, index) => {
      const points = group.ids.reduce((sum, id) => sum + answers[id - 1], 0);
      total += points;
      return {...group, index, mean: points / group.ids.length};
    }).sort((a,b) => b.mean - a.mean);
    const selected = ranked.filter(group => group.mean >= 3.5 && ranked[0].mean - group.mean <= 0.50000001);
    const mask = selected.reduce((sum, group) => sum + (1 << group.index), 0);
    return {...profile,total,ranked,selected,subtitle: mask ? profile.titles[titles[mask]] : '倾向较轻'};
  }).sort((a,b) => b.total - a.total);
}

